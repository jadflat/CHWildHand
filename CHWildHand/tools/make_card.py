"""Builds WILDHAND.DAT, the game's file on the SD card, and the headers the game is compiled against.

  block 0       "WILDHAND", the build's hash (a CRC-32 of the rest)
  CARD_ART      every picture of Art.h and Art2.h (run-length rows), packed so that no picture crosses a 512 B block
  CARD_SONG     the songs of Music.h, each from a block boundary, in 64-step chunks of 192 bytes (lead, bass, drums,
                64 steps each), two chunks a 512 B block: the game streams a song a chunk at a time (Synth.cpp)
  CARD_TEXT     the shop's text (tools/card_text.py), a 512 B block of NUL-terminated strings a group
  CARD_STAGE    the bonus stages that are scripts (tools/stages/*.stg, tools/stage_asm.py; StageVM.h runs them): a directory, the blobs;
                their text is one more text block after card_text.GROUPS (STAGE_TXG)
  CARD_SFX      the sound effects (tools/sfx_src.txt): start steps, flags, steps; then the wild cards' rule table (tools/jokers.py);
                loaded into RAM when the card opens
  CARD_SET      the last block, 0xFF: the pause menu's settings are kept here (Card.cpp putSettings), so another game's save cannot
                take them; not in the hash, and the game never writes any other block of the file

Reads Art.h (tools/art.py), Art2.h (tools/art2.py) and Music.h (tools/make_music.py) and writes:
  ArtCard.h     Art.h + Art2.h with each picture replaced by its offset in CARD_ART (drawArt reads it from the card)
  MusicCard.h   Music.h without the note streams; each song keeps its instruments, tempo and echo
  CardIndex.h   the hash and the sections' offsets
  ../dist/WILDHAND.DAT and ../sdcard/WILDHAND.DAT (the simulator's card)

Run: python tools/make_card.py   (from CHWildHand/CHWildHand; rerun after any art or music change)
"""
import os
import re
import struct
import zlib
import songs as sg_cfg                           # PUBLIC=1: only the original songs (tools/songs.py)

HERE = os.path.dirname(os.path.abspath(__file__))
SK = os.path.join(HERE, '..')
ROOT = os.path.join(SK, '..')
SONG_STRIDE = 8                               # blocks a song takes (the longest: 16 chunks = 8 blocks): song n starts at block 8n
ARR = re.compile(r'static const (?:int8_t|uint8_t) (\w+)\[\d*\] = \{([^}]*)\};\n')


def padded(b):
    return b + bytes(-len(b) % 512)


def nums(body):
    return [int(v) for v in body.replace('\n', ' ').split(',') if v.strip()]


# ---- the pictures
art, order = {}, []
keep = []                                     # the text of Art.h/Art2.h that stays in flash
for fn in ('Art.h', 'Art2.h'):
    src = open(os.path.join(SK, fn)).read()
    rest, last = [], 0
    for m in ARR.finditer(src):
        name = m.group(1)
        if name.startswith('ART_'):
            art[name] = bytes(nums(m.group(2)))
            order.append(name)
            rest.append(src[last:m.start()])
            last = m.end()
    rest.append(src[last:])
    keep.append(''.join(rest).replace('#pragma once', '').replace('// Generated by', '// (from'))
# the play screen's pictures first (court cards, dealers, wild cards), then the rest; none crosses a block. The newer dealers (D6-D8) go last:
# the older pictures keep their places (and the code its short offsets)
pri = lambda n: 4 if n in ('ART_D6', 'ART_D7', 'ART_D8') else 0 if n in ('ART_JACK', 'ART_QUEEN', 'ART_KING') else 1 if n.startswith('ART_D') else 2 if n.startswith('ART_W') else 3
order.sort(key=pri)
pics, where = bytearray(), {}
for n in order:
    b = art[n]
    assert len(b) <= 512, n
    if (len(pics) % 512) + len(b) > 512:
        pics += bytes(-len(pics) % 512)
    where[n] = len(pics)
    pics += b

# ---- the songs
msrc = open(os.path.join(SK, 'Music.h')).read()
streams = {m.group(1): nums(m.group(2)) for m in ARR.finditer(msrc) if re.search(r'_(LEAD|BASS|DRUMS)$', m.group(1))}
tab = re.search(r'static const SongHdr SONGS\[SYN_SONGS\] = \{\n(.*?)\n\};', msrc, re.S)
rows = re.findall(r'\{ (\w+)_LEAD, \w+_BASS, \w+_DRUMS, (\w+), (\d+), (\d+), (\d+) \}', tab.group(1))
insts = {m.group(1): [int(x) for x in re.findall(r'\d+', m.group(2))] for m in re.finditer(r'static const Inst (\w+)\[3\] = \{(.*?)\};\n', msrc)}
songs, hdr = bytearray(), []
for name, inst, ms, dl, steps in rows:
    steps = int(steps)
    v = [streams['%s_%s' % (name, part)] for part in ('LEAD', 'BASS', 'DRUMS')]
    assert all(len(x) == steps for x in v) and steps % 64 == 0 and steps <= 1024 and int(dl) < 16, name
    assert all(0 <= n < 128 for x in v for n in x), name
    ins = insts[inst]
    assert len(ins) == 21 and int(ms) < 510, name
    assert len(songs) % (SONG_STRIDE * 512) == 0
    s0 = len(songs)
    for c in range(steps // 64):                  # a chunk: lead, bass, drums, 64 steps each; two chunks a block
        songs += b''.join(bytes(x[c * 64:c * 64 + 64]) for x in v)
        if c & 1:
            songs += bytes(512 - 384)
    if len(songs) % 512:
        songs += bytes(512 - len(songs) % 512)
    # the song's header at 384 of its first block: the three instruments, the step length in 2 ms, the echo delay, the chunks
    songs[s0 + 384:s0 + 408] = bytes(ins) + bytes([(int(ms) + 1) // 2, int(dl), steps // 64])
    songs += bytes(SONG_STRIDE * 512 - len(songs) % (SONG_STRIDE * 512)) if len(songs) % (SONG_STRIDE * 512) else b''
    hdr.append(name)
mout = msrc[:tab.start()]
for k in streams:
    mout = re.sub(r'static const uint8_t %s\[\d+\] = \{[^}]*\};\n' % k, '', mout)
mout = re.sub(r'static const Inst \w+_INST\[3\] = \{.*?\};\n', '', mout)
mout = re.sub(r'struct SongHdr \{.*?\n', '', mout)
mout = mout.replace('// Generated by tools/make_music.py', '// Generated by tools/make_card.py from Music.h (tools/make_music.py): the notes, instruments and tempi are on the SD card (CARD_SONG)')

pics = padded(bytes(pics))
songs = padded(bytes(songs))

# ---- the text (tools/card_text.py): one 512 B block of NUL-terminated strings a group, after the songs
import card_text
import stage_asm                               # the scripted stages: their section, and their text as one more group
stages, stage_txt, stage_n, _ = stage_asm.build()
texts = b''
for g in card_text.GROUPS + [stage_txt]:
    tb = g if isinstance(g, bytes) else b''.join(t.encode('ascii') + b'\0' for t in g)   # (the colour block is bytes: tools/colours.py)
    assert len(tb) <= 512, 'a text group is longer than a block'
    texts += padded(tb)
# ---- the sound effects (tools/sfx_src.txt, the old Sounds.cpp): [start step of each effect + the end: COUNT+1 bytes][flags: COUNT]
# [the steps: hz, endHz (20 Hz units), ms (2 ms units)], read into RAM once when the card is opened (Sounds.cpp)
ssrc = open(os.path.join(HERE, 'sfx_src.txt')).read()
tabs = {}
for m in re.finditer(r'AUDIO_STEPS\((\w+)\)\s*=\s*\{(.*?)\};', ssrc, re.S):
    st = []
    for k in re.finditer(r'AUDIO_(STEP|REST)\(([^)]*)\)', m.group(2)):
        a = [int(x) for x in k.group(2).split(',')]
        st += [(a[0] + 10) // 20, (a[1] + 10) // 20, (a[2] + 1) // 2] if k.group(1) == 'STEP' else [0, 0, (a[0] + 1) // 2]
    tabs[m.group(1)] = st
efx = re.findall(r'AUDIO_EFFECT\((\w+), ([^)]*?)\)', ssrc.split('const audio::Effect SOUNDS')[1])
fl = {'audio::GLIDE': 0x20, 'audio::SOFT': 0x10}
starts, flags, stepb = [], [], []
for nm, f in efx:
    starts.append(len(stepb) // 3)
    stepb += tabs[nm]
    flags.append(sum(fl.get(p.strip(), 0) or int(p) for p in f.split('|')))
starts.append(len(stepb) // 3)
assert len(starts) < 256 and all(v < 256 for v in stepb)
import jokers                                   # the wild cards' rule table follows the sound tables in the same RAM block
jt = jokers.table(lambda i: where['ART_W%d' % i])
misc = b''.join(t.encode('ascii') + bytes(1) for t in card_text.MISC)
import tables                                  # and the RAM tables (tools/tables.py) after the text
artTabs = []                                   # Art.h's glyph tables named in tables.FROM_ART go to RAM too: ArtCard.h gets a #define instead
for name, dim in tables.FROM_ART:
    for i, k in enumerate(keep):
        m = re.search(r'static const uint8_t %s\[\d+\]\[\d+\] = \{(.*?)\};\n' % name, k, re.S)
        if m:
            artTabs.append((name, bytes(int(v, 0) for v in re.findall(r'0x[0-9A-Fa-f]+|\d+', m.group(1)))))
            keep[i] = k[:m.start()] + '#define %s ((const uint8_t (*)[%d])(wh_tabs + T_%s))   // (in RAM, from the card: tools/tables.py)\n' % (name, dim, name) + k[m.end():]
            break
    else:
        raise SystemExit('no table ' + name)
tab, taboff = tables.table(artTabs)
sfx = padded(bytes(starts) + bytes(flags) + bytes(stepb) + jt + misc + tab)
sfx_len = len(starts) + len(flags) + len(stepb)
art_blk = 1
song_blk = art_blk + len(pics) // 512
stages = padded(stages)
body = pics + songs + texts + sfx + stages
h = zlib.crc32(body) & 0xffffffff
head = padded(b'WILDHAND' + struct.pack('<I', h))
dat = head + body + bytes([0xFF]) * 512                 # (the settings block: after the hashed part)
for d in (os.path.join(ROOT, 'dist') if not sg_cfg.PUBLIC else os.path.join(ROOT, 'dist', 'public'), os.path.join(SK, 'sdcard')):
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'WILDHAND.DAT'), 'wb').write(dat)

out = ['// Generated by tools/make_card.py: do not edit. The pictures are on the SD card (WILDHAND.DAT, CARD_ART);',
       '// each ART_ name is its offset there, which drawArt() reads through the card cache.', '#pragma once', '#include <stdint.h>']
out += ['#define %s ((const uint8_t *)(uintptr_t)%d)' % (n, where[n]) for n in sorted(where)]
out += [k.strip() for k in keep]
open(os.path.join(SK, 'ArtCard.h'), 'w', newline='').write('\n'.join(out) + '\n')
open(os.path.join(SK, 'MusicCard.h'), 'w', newline='').write(mout)
open(os.path.join(SK, 'CardIndex.h'), 'w', newline='').write(
    '// Generated by tools/make_card.py: WILDHAND.DAT\'s hash and where its sections start (byte offsets).\n'
    '#pragma once\n#include <stdint.h>\n\n'
    'static const uint32_t CARD_HASH = 0x%08Xu;\n'
    'static const uint32_t CARD_ART = %d, CARD_SONG = %d, CARD_TEXT = %d, CARD_SFX = %d, CARD_SET = %d;\n'
    'static const uint32_t CARD_STAGE = %d;\n'
    'static const uint8_t STAGE_N = %d, STAGE_TXG = %d, STAGE_STRS = %d;\n'
    'static const uint16_t SFX_LEN = %d, SFX_COUNT = %d, JT_LEN = %d, MISC_LEN = %d, TAB_LEN = %d, %s;\n' % (h, art_blk * 512, song_blk * 512, song_blk * 512 + len(songs),
                                                         song_blk * 512 + len(songs) + len(texts), len(dat) - 512,
                                                         song_blk * 512 + len(songs) + len(texts) + len(sfx), stage_n, len(card_text.GROUPS), len(stage_txt), sfx_len, len(efx), len(jt), len(misc), len(tab), ', '.join('%s = %d' % kv for kv in taboff.items())))
import colours                                 # the colour block's offsets (Gfx.h applyCol)
counts = ['%s = %d' % kv for kv in colours.data()[1].items()] + ['CT_JSPLIT = %d' % card_text.JSPLIT] + ['CT_G%d = %d' % (i, len(g)) for i, g in enumerate(card_text.GROUPS)] + ['CT_MISC = %d' % len(card_text.MISC)]
open(os.path.join(SK, 'CardIndex.h'), 'a', newline='').write('// how many strings each text group holds (card_text.py GROUPS and MISC); the sketch static_asserts its TX_* enums against these\n'
    'static constexpr uint16_t %s;\n' % ', '.join(counts))
print('WILDHAND.DAT: %d bytes (hash %08X): %d pictures in %d blocks, %d songs' % (len(dat), h, len(where), len(pics) // 512, len(rows)))
open(os.path.join(SK, 'CardIndex.h'), 'a', newline='').write('// which song plays where, and the version (tools/songs.py)\n' + ''.join('#define SG_%s %d\n' % kv for kv in sg_cfg.ID.items()) +
    '#define NSTAGE %d                                        // the stage songs\n#define WH_VERSTR "V%s"\n' % (len(sg_cfg.KSONG), sg_cfg.VERSION))
